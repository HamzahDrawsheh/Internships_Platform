function flattenLeaves(obj: Record<string, unknown>, prefix = ""): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [key, value] of Object.entries(obj)) {
    const path = prefix ? `${prefix}.${key}` : key;
    if (typeof value === "string") {
      out[path] = value;
    } else if (value && typeof value === "object") {
      Object.assign(out, flattenLeaves(value as Record<string, unknown>, path));
    }
  }
  return out;
}

export function buildPhrasePairs(): Array<[string, string]> {
  const enFlat = flattenLeaves(messages.en as Record<string, unknown>);
  const arFlat = flattenLeaves(messages.ar as Record<string, unknown>);
  const pairs: Array<[string, string]> = [];

  for (const [key, enText] of Object.entries(enFlat)) {
    const arText = arFlat[key];
    if (arText && arText !== enText) {
      pairs.push([enText, arText]);
    }
  }

  for (const [en, ar] of extraPhrasePairs) {
    if (en && ar && en !== ar) pairs.push([en, ar]);
  }

  return pairs.sort((a, b) => b[0].length - a[0].length);
}

export function translatePhrase(text: string, locale: Locale): string {
  if (locale === "en" || !text) return text;

  const trimmed = text.trim();
  const enFlat = flattenLeaves(messages.en as Record<string, unknown>);
  const arFlat = flattenLeaves(messages.ar as Record<string, unknown>);

  for (const [key, enText] of Object.entries(enFlat)) {
    if (enText === trimmed) {
      const arText = arFlat[key];
      if (arText) return text.replace(trimmed, arText);
    }
  }

  for (const [en, ar] of extraPhrasePairs) {
    if (en === trimmed) return text.replace(trimmed, ar);
  }

  return text;
}

export function getMessage(locale: Locale, key: string): string {
  const parts = key.split(".");
  let node: unknown = messages[locale];
  for (const part of parts) {
    if (!node || typeof node !== "object") return key;
    node = (node as Record<string, unknown>)[part];
  }
  return typeof node === "string" ? node : key;
}
